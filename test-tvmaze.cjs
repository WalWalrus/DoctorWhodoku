const assert=require('node:assert/strict');
const fs=require('node:fs');
const E=require('./editor-data.js');
const base=Object.fromEntries(['characters','episodes','appearances','categories'].map(k=>[k,JSON.parse(fs.readFileSync(__dirname+'/'+k+'.json'))]));
const original=JSON.stringify(base);
const episode={id:100,name:base.episodes[0].title,season:1,number:1,type:'regular',airdate:base.episodes[0].ukAirDate};
const special={id:101,name:'Test special',season:2,number:null,type:'significant_special',airdate:'2006-12-25'};
const cast=[{character:{id:200,name:'Rose Tyler'}},{character:{id:201,name:'Test companion'}},{character:{id:202,name:'The Ninth Doctor'}}];
const files=[{name:'any-episodes.json',value:[episode,special]},{name:'characters.json',value:cast}];
const batch=E.readBatch(files,base), result=E.merge(base,batch);
assert.deepEqual(E.validate(result.candidate),[]);
assert.equal(result.counts.added.episodes,1);assert.equal(result.counts.added.characters,1);
assert.equal(batch.characters.find(c=>c.externalIds.tvmaze===202).id,'ninth-doctor');
assert.equal(batch.episodes[0].id,base.episodes[0].id);
assert.equal(batch.episodes[1].series,'specials');assert.ok(!('episodeNumber' in batch.episodes[1]));
assert.deepEqual(result.candidate.appearances,base.appearances);
for(const c of base.characters)assert.deepEqual(result.candidate.characters.find(x=>x.id===c.id).storyTraits,c.storyTraits);
assert.equal(JSON.stringify(base),original);
const again=E.merge(result.candidate,E.readBatch(files,result.candidate));
assert.deepEqual(again.candidate,result.candidate);
const ambiguous=E.readBatch([{name:'cast.json',value:[{character:{id:210,name:'The Master'}},{character:{id:211,name:'The Master'}},{character:{id:212,name:'The Doctor'}}]}],base);
assert.equal(ambiguous.characters.length,0);assert.equal(ambiguous.importNotes.filter(x=>x.startsWith('Skipped')).length,3);
assert.equal(E.readBatch([{name:'cast.json',value:[cast[0],cast[0]]}],base).characters.length,1);
assert.throws(()=>E.readBatch([{name:'cast.json',value:[cast[0],{}]}],base),/Invalid TVmaze/);
assert.throws(()=>E.merge(base,{characters:[{name:'Missing ID'}]}),/text ID/);
assert.deepEqual(E.merge(base,E.readBatch([{name:'episodes.json',value:base.episodes}],base)).candidate,base);
console.log('PASS: TVmaze detection, matching, repeat imports, specials, ambiguous identities, malformed data, native imports and preservation of links/facts.');
